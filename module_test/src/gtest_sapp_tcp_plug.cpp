extern "C" char tcpall_first_unorder_pkt_entry(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	static int pkt_index = 0;
	int ret, pkt_tot_len;
	void *raw_pkt_hdr;

	pkt_index++;

	/* 乱序包设成3,   pcap第9个包是第4个带负载的包, 会强制把前三个包从乱序缓冲队列中挤出去 */
	if(9 == pkt_index){
		ret = get_rawpkt_opt_from_streaminfo(pstream, RAW_PKT_GET_DATA, &raw_pkt_hdr);
		if(ret < 0){
			printf("\033[1;31;40mtcpall_first_unorder_pkt_entry(): get_rawpkt_opt_from_streaminfo()->RAW_PKT_GET_DATA error!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;		
		}

		ret = get_rawpkt_opt_from_streaminfo(pstream, RAW_PKT_GET_TOT_LEN, &pkt_tot_len);
		if(ret < 0){
			printf("\033[1;31;40mtcpall_first_unorder_pkt_entry(): get_rawpkt_opt_from_streaminfo()->RAW_PKT_GET_TOT_LEN error!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;		
		}

		if(pkt_tot_len != 1514){
			printf("\033[1;31;40mtcpall_first_unorder_pkt_entry(): tot_pkt_len is:%d, but expect 1514!\033[0m\n", pkt_tot_len);
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}

		const struct ip *ip4_hdr = (struct ip *)((char *)raw_pkt_hdr + sizeof(struct ethhdr)+4+4/*mpls hdr*/);
		if(ntohs(ip4_hdr->ip_id) != 0xD978){
			printf("\033[1;31;40mtcpall_first_unorder_pkt_entry(): ipv4 ipid is:0x%x, but expect 0xD978\033[0m\n", ntohs(ip4_hdr->ip_id));
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}
		if(ntohs(ip4_hdr->ip_sum) != 0xD1A0){
			printf("\033[1;31;40mtcpall_first_unorder_pkt_entry(): ipv4 ip checksum is:0x%x, but expect 0xD1A0\033[0m\n", ntohs(ip4_hdr->ip_sum));
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}		

		printf("\033[32m tcpall_first_unorder_pkt_entry() test succ!\033[0m\n");
		gtest_set_libsapp_devel_result(GTEST_SAPP_SUCC);	
		return APP_STATE_DROPME;
	}

	return APP_STATE_GIVEME;
}


