extern "C" void hybrid_tcp_destroy(void)
{
	char log_file_cont[99999];
	
	fclose(hybrid_stream_log_fp);

	hybrid_stream_log_fp = fopen(GTEST_HYBRID_STREAM_LOG_FILE, "r");

	fread(log_file_cont, sizeof(log_file_cont), 1, hybrid_stream_log_fp);

	if(memcmp(log_file_cont, hybrid_pure_tcp_log_bin, sizeof(hybrid_pure_tcp_log_bin)) != 0){
		printf("\033[1;31;40mhybrid_tcp_: log file content is different with history!\033[0m\n");
		sendto_test_result(GTEST_SAPP_ERR);
	}else{
		printf("\033[32mhybrid_tcp check succ, file content len:%d!\033[0m\n", (int)sizeof(hybrid_pure_tcp_log_bin));
		sendto_test_result(GTEST_SAPP_SUCC);
	}
}

static int hybrid_first_call = 0;

extern "C" char hybrid_stream_log_entry(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	if(0 == hybrid_first_call){
		hybrid_stream_log_fp = fopen(GTEST_HYBRID_STREAM_LOG_FILE, "w+");
		if(NULL == hybrid_stream_log_fp){
			printf("\033[1;31;40mhybrid_tcp_entry fopen file:%s error, %s\033[0m\n", GTEST_HYBRID_STREAM_LOG_FILE, strerror(errno));
			sendto_test_result(GTEST_SAPP_ERR);
			exit(1);				
		}
		hybrid_first_call = 1;
	}
	
	if(pstream->opstate == OP_STATE_CLOSE){
		fprintf(hybrid_stream_log_fp, "stream:%s,c2s_pkt:%u,c2s_byte:%u,s2c_pkt:%u,s2c_byte:%u\n", 
				printaddr(&pstream->addr, thread_seq),
				pstream->ptcpdetail->serverpktnum, pstream->ptcpdetail->serverbytes,
				pstream->ptcpdetail->clientpktnum, pstream->ptcpdetail->clientbytes);
		fflush(hybrid_stream_log_fp);		
	}
	
	return APP_STATE_GIVEME;
}


