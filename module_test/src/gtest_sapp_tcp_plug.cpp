extern "C" char tcp_simple(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	//struct tcpdetail *pdetail=(struct tcpdetail *)pstream->pdetail;
	
	if(pstream->opstate == OP_STATE_CLOSE){
		if(ntohs(pstream->addr.tuple4_v4->source) != 58725){
			printf("\033[1;31;40mtcp_simple: sport is not 58725!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}
		if(ntohs(pstream->addr.tuple4_v4->dest) != 22){
			printf("\033[1;31;40mtcp_simple: dport is not 22!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}	
		if(ntohl(pstream->addr.tuple4_v4->saddr) != 0xC0A80AFA){
			printf("\033[1;31;40mtcp_simple: sip is not 192.168.10.250!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}			
		if(ntohl(pstream->addr.tuple4_v4->daddr) != 0xC0A80AEA){
			printf("\033[1;31;40mtcp_simple: dip is not 192.168.10.234!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
			return APP_STATE_DROPME;
		}			
		if((16 == gtest_tcp_stat.C2S_data_pkt)
		 &&(2329 == gtest_tcp_stat.C2S_data_byte)
		 &&(30 == gtest_tcp_stat.S2C_data_pkt)
		 &&(11345 == gtest_tcp_stat.S2C_data_byte)){
		 	printf("\033[32m tcp_simple() test succ!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_SUCC);
		}else{
			printf("\033[1;31;40mtcp_simple: check data error!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
		}
	}else{
		tcp_pkt_stat(pstream, pme, thread_seq, a_packet);
	}
	
	return APP_STATE_GIVEME;
}

