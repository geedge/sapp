extern "C" char hybrid_pure_udp_entry(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	static int hybrid_udp_first_call = 0;

	if(0 == hybrid_udp_first_call){
		hybrid_stream_log_fp = fopen(GTEST_HYBRID_STREAM_LOG_FILE, "w+");
		if(NULL == hybrid_stream_log_fp){
			printf("\033[1;31;40mhybrid_udp_entry fopen file:%s error, %s\033[0m\n", GTEST_HYBRID_STREAM_LOG_FILE, strerror(errno));
			sendto_test_result(GTEST_SAPP_ERR);
			exit(1);				
		}
		hybrid_udp_first_call = 1;
	}
	
	if(pstream->opstate == OP_STATE_CLOSE){
		fprintf(hybrid_stream_log_fp, "stream:%s,c2s_pkt:%u,c2s_byte:%u,s2c_pkt:%u,s2c_byte:%u\n", 
				printaddr(&pstream->addr, thread_seq),
				pstream->ptcpdetail->serverpktnum, pstream->ptcpdetail->serverbytes,
				pstream->ptcpdetail->clientpktnum, pstream->ptcpdetail->clientbytes);
		fflush(hybrid_stream_log_fp);		
	}
	
	return APP_STATE_GIVEME;
}

extern "C" char cheat_l2tp_dup_check_entry(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	static int this_plug_call_times = 0;
	unsigned short stream_tunnel_type;
	int opt_len = sizeof(short);
	
	MESA_get_stream_opt(pstream, MSO_STREAM_TUNNEL_TYPE, &stream_tunnel_type, &opt_len);
	if(stream_tunnel_type != STREAM_TUNNLE_L2TP){
		return APP_STATE_DROPME; /* 只处理l2tp隧道内部流量 */
	}

	if(a_packet != NULL){
		this_plug_call_times++;
	}
	
	if(pstream->opstate == OP_STATE_CLOSE){
		if(this_plug_call_times != 4){ /* l2tp_cheat_dup_dns.pcap 实际有4个数据包, 并不是重复的 */
			printf("\033[1;31;40m cheat_l2tp_dup_check_entry() check error, expect 4 pkt, but actual is:%d\033[0m\n", this_plug_call_times);
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);			
		}else{
			printf("\033[32m cheat_l2tp_dup_check_entry() test succ!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_SUCC);
		}
	}
	
	return APP_STATE_GIVEME;
}


