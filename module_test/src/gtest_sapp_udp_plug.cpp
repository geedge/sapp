			printf("\033[1;31;40mudp_simple_entry() error, S2C_all_pkt is:%u, but expect %d\033[0m\n", gtest_udp_stat.S2C_all_pkt, 665);
			gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);	
