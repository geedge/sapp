static char *get_file_md5sum(const char *filename, char *md5sum, int buflen)
{
	FILE *cmd_res_fp;
	char cmd_buf[1024];
	//int ret = 0;

	if(buflen < 33){
		return NULL;
	}
	memset(md5sum, 0, buflen);

	snprintf(cmd_buf, 1024, "%s %s", "md5sum", filename);

	cmd_res_fp = popen(cmd_buf, "r");
	if(NULL == cmd_res_fp){
		return NULL;
	}

	fgets(md5sum, 33, cmd_res_fp);

	fclose(cmd_res_fp);

	return md5sum;
}


