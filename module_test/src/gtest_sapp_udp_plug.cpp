static int udp_timeout_stream_num = 0;
extern "C" char udp_timeout_reset_entry(struct streaminfo *pstream,void **pme, int thread_seq, void *a_packet)
{
	//printf("pstream:%p, state:%d, dir:%d\n", pstream, pstream->opstate, pstream->dir);
	if(OP_STATE_PENDING == pstream->opstate){
		udp_timeout_stream_num++;
	}

	if(OP_STATE_CLOSE == pstream->opstate){
		if(1 == udp_timeout_stream_num){
			if(DIR_DOUBLE != pstream->dir){
				printf("\033[1;31;40m udp_timeout_reset_entry() check error, the first stream dir is:%d, not double\033[0m\n", pstream->dir);
				gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
				return APP_STATE_DROPME;
			}
			if(3 != pstream->pudpdetail->serverpktnum){
				printf("\033[1;31;40m udp_timeout_reset_entry() check error, the first stream C2S pkt:%u, not 3\033[0m\n", pstream->pudpdetail->serverpktnum);
				gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
				return APP_STATE_DROPME;
			}	
			if(3 != pstream->pudpdetail->clientpktnum){
				printf("\033[1;31;40m udp_timeout_reset_entry() check error, the first stream S2C pkt:%u, not 3\033[0m\n", pstream->pudpdetail->clientpktnum);
				gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
				return APP_STATE_DROPME;
			}			
		}
		if(2 == udp_timeout_stream_num){
			if(DIR_C2S != pstream->dir){
				printf("\033[1;31;40m udp_timeout_reset_entry() check error, the second stream dir is:%d, not C2S\033[0m\n", pstream->dir);
				gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
				return APP_STATE_DROPME;
			}

			if(2 != pstream->pudpdetail->serverpktnum){
				printf("\033[1;31;40m udp_timeout_reset_entry() check error, the second stream C2S pkt:%u, not 2\033[0m\n", pstream->pudpdetail->serverpktnum);
				gtest_set_libsapp_devel_result(GTEST_SAPP_ERR);
				return APP_STATE_DROPME;
			}
			

			printf("\033[32m udp_timeout_reset_entry() test succ!\033[0m\n");
			gtest_set_libsapp_devel_result(GTEST_SAPP_SUCC);			
		}

	}
	
	return APP_STATE_GIVEME;
}


