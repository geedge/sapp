int test_pkt_dump_run(void)
{
	int file_max_size = 32; //MB
	const char *pkt_root_path = "/tmp/pkt_dump/";
	char file_max_size_string[64];
	char dump_file0_name[PATH_MAX];
	char dump_file1_name[PATH_MAX];
	int ret;
	long file_size;
	long try_to_sapp_file_size = 0;
	int chk_res = 0;
	char *sapp_args[2] = {(char *)"sapp", (char *)0};
	int test_pkt_dump_tap_fd;
	
	sprintf(file_max_size_string, "%d", file_max_size);
	set_default_config();
	
	/* 关闭sapp的polling功能 */
	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.polling", 1, "enabled", "0");  
	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.polling", 2, "enabled", "0");  

	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.internal.interface", 1, "type", "pcap");
	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.internal.interface", 2, "type", "pcap");
	
	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.internal.interface", 1, "name", "tap_pkt_dump");
	update_config_file_by_lastNline("etc/sapp.toml", "packet_io.internal.interface", 2, "name", "tap_pkt_dump");
	
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump", 1, "enabled", "1");  
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump", 2, "mode", "storage");  
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump", 3, "mode", "storage"); 

	/* sed 修改源文件, 有'/'符号需要转义 */
	/* 
		16进制 字符
		0x22   "
		0x2F   /
	*/	
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 1, "path", "\\x22\\x2Ftmp\\x2Fpkt_dump\\x22"); 
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 2, "path", "\\x22\\x2Ftmp\\x2Fpkt_dump\\x22");
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 3, "path", "\\x22\\x2Ftmp\\x2Fpkt_dump\\x22");

	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 1, "file_size_max_per_thread", file_max_size_string);
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 2, "file_size_max_per_thread", file_max_size_string);
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 3, "file_size_max_per_thread", file_max_size_string);
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 4, "file_size_max_per_thread", file_max_size_string);
	update_config_file_by_lastNline("etc/sapp.toml", "tools.pkt_dump.storage", 5, "file_size_max_per_thread", file_max_size_string);

	update_conflist_inf("\n"); 
	
	test_pkt_dump_tap_fd = tuntap_dev_create((char *)"tap_pkt_dump", IFF_TAP | IFF_MULTI_QUEUE | IFF_NO_PI);
	if(test_pkt_dump_tap_fd < 0){
		printf("tuntap_dev_create() %s error!\n", "tap_pkt_dump");
		return -1;
	}	

	system("rm -f /tmp/gtest_pkt_dump/*.pcap");

	snprintf(dump_file0_name, PATH_MAX, "%s/pid_%d.tid_%d.%d.pcap",  pkt_root_path, getpid(), 0, 0);
	snprintf(dump_file1_name, PATH_MAX, "%s/pid_%d.tid_%d.%d.pcap",  pkt_root_path, getpid(), 0, 1);

	
	libsapp_setup_env(1, sapp_args);
	
	while(1){
		usleep(1);
		ret = write(test_pkt_dump_tap_fd, g_icmp_pcap_binary, sizeof(g_icmp_pcap_binary));
		if(ret >= 0){
			try_to_sapp_file_size += ret + sizeof(struct pcap_pkthdr);
		}
		
		file_size = gtest_get_file_length(dump_file0_name); //超过 file_max_size要重新写文件.1
		if(file_size >= file_max_size*1024*1024){
			sync();
			ret = gtest_if_file_exist(dump_file1_name);
			if(ret <= 0){
				printf("\033[1;31;40m %s exceed threshold, but has not found %s !\033[0m\n", dump_file0_name, dump_file1_name);
				chk_res = -1;
			}else{
				chk_res = 0;
			}
			break;
		}
		
		if(try_to_sapp_file_size > file_max_size*1024*1024 * 10){
			/* 因为pcap捕包模式可能丢包, 但是实际发送的数据比pkt_dump的大了10倍, 实际保存的文件也没超过file_max_size, 可能是个bug，不要再重复尝试了 */
			printf("\033[1;31;40m try send to sapp %ld bytes, but file pid_*.0.pcap is: %ld\033[0m\n", try_to_sapp_file_size, file_size);
			chk_res = -1;
			break;
		}
	}
	libsapp_destroy_env();
	
	return chk_res;
	
}


