void sapp_generate_sample_config(void)
{
	FILE *fp;

	fp = fopen(default_config_file, "w+");
	if(NULL == fp){
		printf("\033[1;31;40m[Error]open %s error, %s!\033[0m\n", default_config_file, strerror(errno));
		return;
	}

	fwrite(sample_sapp_toml, sizeof(sample_sapp_toml), 1, fp);

	fclose(fp);

	printf("\033[32mThe sample config file saved to ./etc/sapp.toml,\033[0m\n");
	printf("\033[32mYou should change some parameters to suit the current system environment!\033[0m\n");
}


int sapp_parse_config(void)
{
	int ret;
	int tmp_int;
	
	if(0 == is_file_exist(default_config_file)){
		special_usage();
		exit(1);
	}

	sapp_global_val = (sapp_global_t *)calloc(1, sizeof(sapp_global_t));

	tomlc99_wrap_load_string_def(default_config_file, (char *)"SYSTEM", (char *)"instance_name", sapp_global_val->config.system.instance_name, NAME_MAX, "sapp_v4.0");
	tomlc99_wrap_load_int_def(default_config_file, (char *)"CPU", (char *)"worker_threads", (int *)&sapp_global_val->config.cpu.worker_threads, 1);
	tmp_int = SAPP_MAX_THREADS;
	ret = tomlc99_wrap_load_long_array(default_config_file, (char *)"CPU", (char *)"bind_mask", sapp_global_val->config.cpu.bind_mask_array, &tmp_int);
	if(ret < 0){
		memset(sapp_global_val->config.cpu.bind_mask_array, 0, sizeof(sapp_global_val->config.cpu.bind_mask_array));
	}else{
		sapp_global_val->config.cpu.bind_mask = tomlc99_long_array_combination(sapp_global_val->config.cpu.bind_mask_array, tmp_int);
	}

	return 0;
}

