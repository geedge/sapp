static inline int is_file_exist(const char *filename)
{
	struct stat fstat;
	int fres, ret;

	fres = stat(filename, &fstat);
	if(fres < 0){
		if(ENOENT == errno){
			ret = 0;
		}
	}else{
		ret = 1;
	}

	return ret;
}

